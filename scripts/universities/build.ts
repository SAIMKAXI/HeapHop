// Builds the university list from hec-names.txt and short-forms.ts into:
//   supabase/migrations/20261122085155_universities_seed.sql   (loads it into the database)
//   tests/e2e/universities.json                                 (the same list, for the fake Supabase)
// Run with: npx tsx scripts/universities/build.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { SHORT_FORMS } from "./short-forms";
import { uniKey } from "../../src/ui/auth/university-search";

const root = join(import.meta.dirname, "..", "..");
const lines = readFileSync(join(import.meta.dirname, "hec-names.txt"), "utf8").split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));

const list = lines.map((line) => {
  const brackets = [...line.matchAll(/\(([^)]+)\)/g)].map((m) => m[1].trim());
  const name = line.replace(/\s*\([^)]*\)/g, "").replace(/\s+,/g, ",").replace(/\s+/g, " ").trim();
  return { name, aliases: [...brackets] };
});

const byName = new Map(list.map((u) => [u.name, u]));
for (const [name, forms] of Object.entries(SHORT_FORMS)) {
  const u = byName.get(name);
  if (!u) throw new Error(`short-forms.ts names a university that is not in hec-names.txt: ${name}`);
  u.aliases.push(...forms);
}
const seen = new Map<string, string>();
for (const u of list) {
  const k = uniKey(u.name);
  if (seen.has(k)) throw new Error(`two names reduce to the same key: ${seen.get(k)} / ${u.name}`);
  seen.set(k, u.name);
  if (u.name.length > 120 || /[<>{}[\]`$]/.test(u.name)) throw new Error(`name not allowed: ${u.name}`);
  u.aliases = [...new Set(u.aliases)];
  if (u.aliases.length > 12) throw new Error(`too many short forms: ${u.name}`);
}
list.sort((a, b) => a.name.localeCompare(b.name));

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const rows = list.map((u) => `  (${q(u.name)}, array[${u.aliases.map(q).join(", ")}]::text[])`).join(",\n");
const sql = `-- Generated by scripts/universities/build.ts from scripts/universities/hec-names.txt and
-- short-forms.ts. Do not edit by hand: change those and run the script again.
-- ${list.length} HEC-recognised universities and degree-awarding institutes.

insert into public.universities (name, aliases) values
${rows}
on conflict (name) do update set aliases = excluded.aliases;

select private.rebuild_university_keys();
select private.rematch_unlisted();
`;
writeFileSync(join(root, "supabase", "migrations", "20261122085155_universities_seed.sql"), sql);
writeFileSync(join(root, "tests", "e2e", "universities.json"), JSON.stringify(list, null, 1) + "\n");
console.log(`${list.length} universities, ${list.reduce((n, u) => n + u.aliases.length, 0)} short forms`);
